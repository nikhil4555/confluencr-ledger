import { ApiProperty } from '@nestjs/swagger';
import { Transform } from 'class-transformer';
import {
  IsEnum,
  IsNotEmpty,
  IsNumber,
  IsPositive,
  IsString,
  MaxLength,
} from 'class-validator';
import { TransactionType } from '@prisma/client';

export class AddTransactionDto {
  @ApiProperty({
    description: 'Transaction type',
    enum: TransactionType,
    example: 'credit',
  })
  @IsEnum(TransactionType, {
    message: 'type must be either "credit" or "debit"',
  })
  type: TransactionType;

  @ApiProperty({
    description: 'Transaction amount (must be > 0, max 2 decimal places)',
    example: 100.5,
    minimum: 0.01,
  })
  @IsNumber(
    { allowInfinity: false, allowNaN: false, maxDecimalPlaces: 2 },
    { message: 'amount must be a valid number with at most 2 decimal places' },
  )
  @IsPositive({ message: 'amount must be greater than 0' })
  amount: number;

  @ApiProperty({
    description: 'Description of the transaction',
    example: 'Salary deposit',
    maxLength: 500,
  })
  @IsString()
  @Transform(({ value }: { value: unknown }) =>
    typeof value === 'string' ? value.trim() : value,
  )
  @IsNotEmpty({ message: 'description must not be empty or whitespace' })
  @MaxLength(500, { message: 'description must not exceed 500 characters' })
  description: string;

  @ApiProperty({
    description:
      'A unique identifier for this transaction scoped to the account. ' +
      'This is an idempotency key — generated by the client before submitting. ' +
      'If the same reference_id is submitted again for the same account (e.g. on a network retry), ' +
      'the server returns the original transaction without creating a duplicate or changing the balance. ' +
      'The same reference_id may be reused across different accounts. ' +
      'Use a UUID or a meaningful business key e.g. "ORDER-20241028-001".',
    example: 'TXN-2024-001',
    maxLength: 255,
  })
  @IsString()
  @Transform(({ value }: { value: unknown }) =>
    typeof value === 'string' ? value.trim() : value,
  )
  @IsNotEmpty({ message: 'referenceId must not be empty or whitespace' })
  @MaxLength(255, { message: 'referenceId must not exceed 255 characters' })
  referenceId: string;
}

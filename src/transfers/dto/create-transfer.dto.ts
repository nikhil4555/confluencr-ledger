import { ApiProperty } from '@nestjs/swagger';
import { Transform } from 'class-transformer';
import {
  IsNotEmpty,
  IsNumber,
  IsPositive,
  IsString,
  IsUUID,
  MaxLength,
} from 'class-validator';

export class CreateTransferDto {
  @ApiProperty({
    description: 'UUID of the source account (funds will be debited from here)',
    example: 'uuid-of-source-account',
  })
  @IsUUID('4', { message: 'fromAccountId must be a valid UUID v4' })
  @IsNotEmpty({ message: 'fromAccountId is required' })
  fromAccountId: string;

  @ApiProperty({
    description: 'UUID of the destination account (funds will be credited here)',
    example: 'uuid-of-destination-account',
  })
  @IsUUID('4', { message: 'toAccountId must be a valid UUID v4' })
  @IsNotEmpty({ message: 'toAccountId is required' })
  toAccountId: string;

  @ApiProperty({
    description: 'Amount to transfer (must be > 0, max 2 decimal places)',
    example: 30.0,
    minimum: 0.01,
  })
  @IsNumber(
    { allowInfinity: false, allowNaN: false, maxDecimalPlaces: 2 },
    { message: 'amount must be a valid number with at most 2 decimal places' },
  )
  @IsPositive({ message: 'amount must be greater than 0' })
  amount: number;

  @ApiProperty({
    description: 'Description of the transfer',
    example: 'Rent payment',
    maxLength: 500,
  })
  @IsString()
  @Transform(({ value }: { value: unknown }) =>
    typeof value === 'string' ? value.trim() : value,
  )
  @IsNotEmpty({ message: 'description must not be empty or whitespace' })
  @MaxLength(500, { message: 'description must not exceed 500 characters' })
  description: string;

  @ApiProperty({
    description:
      'Idempotency key for this transfer. Generated by the client. ' +
      'Submitting the same referenceId again returns the original transfer result without re-executing it. ' +
      'Use a UUID or meaningful business key e.g. "TRANSFER-20241028-001".',
    example: 'TRANSFER-20241028-001',
    maxLength: 255,
  })
  @IsString()
  @Transform(({ value }: { value: unknown }) =>
    typeof value === 'string' ? value.trim() : value,
  )
  @IsNotEmpty({ message: 'referenceId must not be empty or whitespace' })
  @MaxLength(255, { message: 'referenceId must not exceed 255 characters' })
  referenceId: string;
}
